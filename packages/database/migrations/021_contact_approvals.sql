CREATE TABLE IF NOT EXISTS contact_approval_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 0 MINVALUE 0) PRIMARY KEY,
  chat_key text NOT NULL,
  chat_name text NOT NULL,
  context_text text NOT NULL,
  source_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','denied')),
  decided_by text,
  decided_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_contact_approval_pending
  ON contact_approval_requests (chat_key) WHERE status='pending';
